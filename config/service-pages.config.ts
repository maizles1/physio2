export function getServiceLandingPage(slug: string): ServiceLandingPageData | undefined {
  return landingBySlug.get(slug)
}

export function getServiceHref(hubId: string): string {
  const landing = landingByHubId.get(hubId)
  if (landing) return `/services/${landing.slug}`
  const nav = clinicServiceNav.find((item) => item.id === hubId)
  return nav?.href ?? `/services#${hubId}`
}

export function getServiceLandingPaths(): string[] {
  return serviceLandingPages.map((page) => `/services/${page.slug}`)
}

